export function guideSectionIds() {
    return GUIDE_SECTIONS.map(section => section.id);
}

export function findGuideSection(id) {
    const key = String(id ?? '').trim();
    return GUIDE_SECTIONS.find(section => section.id === key) || null;
}

// הסעיפים שמסבירים מסך מסוים בלוח, לפי סדר המדריך.
export function guideSectionsForView(viewId) {
    const key = String(viewId ?? '').trim();
    return GUIDE_SECTIONS.filter(section => section.views.includes(key));
}

// הכתובת של סעיף: #guide/<מזהה>, או #guide למדריך כולו. מזהה לא מוכר
// מחזיר את המדריך כולו, כך שקישור ישן אינו פותח כתובת שבורה.
export function guideHash(sectionId = '') {
    return findGuideSection(sectionId) ? `#${GUIDE_VIEW_ID}/${sectionId}` : `#${GUIDE_VIEW_ID}`;
}

// פירוש הכתובת: null כשאינה של המדריך; אחרת { section } — ריק כשאין סעיף
// או כשהמזהה אינו מוכר.
export function parseGuideHash(hash) {
    const value = String(hash ?? '').replace(/^#/, '');
    const [view, ...rest] = value.split('/');
    if (view !== GUIDE_VIEW_ID) return null;
    let section = rest.join('/');
    try {
        section = decodeURIComponent(section);
    } catch (error) {
        section = '';
    }
    return { section: findGuideSection(section) ? section : '' };
}

// **הדגשה** בתוך טקסט: חלקים זוגיים רגילים, אי־זוגיים מודגשים. סימן שלא
// נסגר מוצג כטקסט, ולא מדגיש את כל ההמשך.
export function splitEmphasis(text) {
    const parts = String(text ?? '').split('**');
    if (parts.length % 2 === 0) {
        const last = parts.pop();
        parts[parts.length - 1] += `**${last}`;
    }
    return parts
        .map((part, index) => ({ text: part, strong: index % 2 === 1 }))
        .filter(part => part.text);
}

function plainText(text) {
    return String(text ?? '').split('**').join('');
}

// כל הטקסט של סעיף, בלי סימני ההדגשה — לחיפוש בתוך המדריך.
export function guideSectionText(section) {
    if (!section) return '';
    const blocks = (section.blocks || []).flatMap(block => block.items || [block.text]);
    return [section.title, section.summary, section.keywords, ...blocks].map(plainText).join(' ');
}

// החיפוש בתוך המדריך: כל מילה של החיפוש חייבת להופיע בסעיף, אחרי קיפול
// העברית של search-suggest.js (ניקוד, גרשיים, סופיות). חיפוש ריק — הכול.
export function filterGuideSections(query, sections = GUIDE_SECTIONS) {
    const tokens = foldHebrew(query).split(' ').filter(Boolean);
    if (!tokens.length) return sections.map(section => section.id);
    return sections
        .filter(section => {
            const haystack = foldHebrew(guideSectionText(section));
            return tokens.every(token => haystack.includes(token));
        })
        .map(section => section.id);
}

// ההודעה לקוראי מסך אחרי חיפוש במדריך.
export function guideFilterMessage(count, total, query) {
    if (!String(query ?? '').trim()) return `${total} סעיפים במדריך.`;
    if (!count) return 'לא נמצא סעיף מתאים. נסו מילה אחרת.';
    if (count === 1) return 'נמצא סעיף אחד.';
    return `נמצאו ${count} סעיפים.`;
}
